-- Helper: check if current user is admin
create or replace view v_current_user_is_admin as
  select exists (
    select 1 from user_roles ur
    join roles r on r.id = ur.role_id
    where ur.auth_user_id = auth.uid() and r.name = 'admin'
  ) as is_admin;

-- Employees: admins can do everything; employees can view/update only their own row (view only in app, updates by admins typically)
create policy employees_admin_all on employees
  for all using ( (select is_admin from v_current_user_is_admin) ) with check ( (select is_admin from v_current_user_is_admin) );

create policy employees_self_select on employees
  for select using ( auth.uid() = auth_user_id );

-- Attendance: admins full; employee can manage their own day records
create policy attendance_admin_all on attendance for all using ( (select is_admin from v_current_user_is_admin) ) with check ( (select is_admin from v_current_user_is_admin) );
create policy attendance_self on attendance for select using (
  exists (select 1 from employees e where e.id = attendance.employee_id and e.auth_user_id = auth.uid())
);
create policy attendance_self_insupd on attendance for insert with check (
