-- Enable UUID extension (if needed)
create extension if not exists "uuid-ossp";

-- Roles and user_roles
create table if not exists roles (
  id bigint generated by default as identity primary key,
  name text unique not null
);

create table if not exists user_roles (
  auth_user_id uuid primary key,
  role_id bigint not null references roles(id) on delete cascade
);

-- Employees
create table if not exists employees (
  id bigint generated by default as identity primary key,
  auth_user_id uuid unique not null references auth.users(id) on delete cascade,
  code text not null unique,
  name text not null,
  dept text,
  designation text,
  base_salary numeric(12,2) default 0
);

-- Attendance
create table if not exists attendance (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references employees(id) on delete cascade,
  date date not null,
  clock_in timestamptz,
  clock_out timestamptz,
  hours_worked numeric(8,2) default 0,
  overtime_hours numeric(8,2) default 0,
  unique(employee_id, date)
);

-- Leave Requests
create table if not exists leave_requests (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references employees(id) on delete cascade,
  start_date date not null,
  end_date date not null,
  reason text,
  status text default 'pending' check (status in ('pending','approved','rejected'))
);

-- Job Cards
create table if not exists job_cards (
  id bigint generated by default as identity primary key,
  employee_id bigint references employees(id) on delete set null,
  description text not null,
  status text default 'assigned' check (status in ('assigned','in_progress','done'))
);

-- Payslips
create table if not exists payslips (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references employees(id) on delete cascade,
  month int not null check (month between 1 and 12),
  year int not null check (year >= 2000),
  base_salary numeric(12,2) not null default 0,
  overtime_pay numeric(12,2) not null default 0,
  deductions numeric(12,2) not null default 0,
  net_pay numeric(12,2) not null default 0,
  pdf_url text
);

-- Invoices and Quotations (simplified)
create table if not exists invoices (
  id bigint generated by default as identity primary key,
  customer text not null,
  amount numeric(12,2) not null,
  status text default 'draft' check (status in ('draft','sent','paid','void')),
  issued_at date default now()
);

create table if not exists quotations (
  id bigint generated by default as identity primary key,
  customer text not null,
  amount numeric(12,2) not null,
  status text default 'draft' check (status in ('draft','sent','accepted','rejected')),
  issued_at date default now()
);

-- Inventory
create table if not exists inventory_items (
  id bigint generated by default as identity primary key,
  name text not null,
  sku text,
  quantity numeric(12,2) not null default 0,
  unit text default 'unit'
);

-- CRM
create table if not exists crm_leads (
  id bigint generated by default as identity primary key,
  name text not null,
  contact text,
  status text default 'new' check (status in ('new','contacted','qualified','lost'))
);

create table if not exists projects (
  id bigint generated by default as identity primary key,
  lead_id bigint references crm_leads(id) on delete set null,
  title text not null,
  status text default 'planning' check (status in ('planning','in_progress','done','on_hold')),
  start_date date,
  end_date date
);

